#!/usr/bin/env python3
"""Extract V's extension mapping without its eagerly initialized MIME database."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("database", type=Path, help="pinned V vlib/net/http/mime/db.v")
    args = parser.parse_args()
    source = args.database.read_bytes()
    table = source.decode().split("const ext_to_mt_str = {", 1)[1].strip()
    assert table.endswith("}")
    entries = []
    for line in table[:-1].splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r"\s*'([^'\\]+)':\s*'([^'\\]+)'\s*", line)
        if not match:
            raise ValueError(f"unexpected extension entry: {line}")
        entries.append(match.groups())
    assert entries and len(dict(entries)) == len(entries)
    entries.sort()
    header = f"""module main

// Generated by tools/generate_mime.py from V's vlib/net/http/mime/db.v.
// Source SHA-256: {hashlib.sha256(source).hexdigest()}
// See doc/THIRD_PARTY.md for attribution. Do not edit by hand.
// A fixed array of string literals needs no heap-backed maps at startup.
const mime_extensions = [
"""
    body = "".join(f"\tMimeEntry{{'{ext}', '{mime}'}}\n" for ext, mime in entries)
    (ROOT / "src/mime_data.v").write_text(header + body + "]!\n")
    print(f"Generated {len(entries)} extension mappings")


if __name__ == "__main__":
    main()
